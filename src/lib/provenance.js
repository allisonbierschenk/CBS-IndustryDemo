// What sits behind each Tableau-powered surface in the portal — shown in its (i) popover:
// freshness, source, security (with the signed-in user's actual JWT attributes) and, in Why Tableau mode,
// a "Why Tableau helps here" paragraph specific to that surface.

const VI_SOURCE = 'Apex Consulting - Client Value Intelligence';
const OPS_SOURCE = 'Apex Consulting - Operational Value & Savings';

/** "client name = Vantage Group · service line = Operations, …" from the user's JWT attributes. */
export function attributeSummary(me, keys) {
  const a = me.user.attributes || {};
  return (keys || Object.keys(a))
    .filter((k) => a[k] && k !== 'subscription tier')
    .map((k) => {
      const v = [].concat(a[k]);
      return `${k} = ${v.length > 3 ? `${v.slice(0, 3).join(', ')} +${v.length - 3}` : v.join(', ')}`;
    })
    .join(' · ');
}

const RLS = (me, keys) =>
  `Row-level security in the published data source, evaluated by Tableau from your sign-in token (${attributeSummary(me, keys)}). The portal never filters data itself.`;

export function provenance(key, me, extra = {}) {
  const ops = key === 'transportation';
  switch (key) {
    case 'valueIntelligence':
    case 'transportation':
      return {
        tag: 'Tableau Embedding API',
        freshness: 'Live: queried from Tableau Cloud each time the dashboard opens, as of the data source’s latest refresh.',
        source: `Published data source “${ops ? OPS_SOURCE : VI_SOURCE}”, embedded with Embedding API v3 and a Connected App token.${ops ? '' : ' The KPI cards are Tableau Pulse metrics.'}`,
        security: RLS(me, ops ? ['client name'] : ['client name', 'service line', 'engagement type']),
        why: ops
          ? 'Freight cost, savings and invoice status all resolve against one governed Operational Value & Savings data source, so the savings on this dashboard and the Transportation Pulse metrics the Agent explains are the same numbers by construction. Client scoping is a data source filter in Tableau, so this dashboard, Pulse and data feeds are limited to your company by one rule rather than one rule per screen.'
          : 'The Pulse cards at the top and the engagement charts below resolve against the same published data source, so they agree by construction rather than because someone checked. The Service Line and Engagement Type filters above are the dashboard’s own Tableau filters — the portal just drives them — and row-level security narrows each one to your scope without the portal writing a single query.'
      };
    case 'report':
      return {
        tag: 'Tableau Embedding API',
        freshness: 'Live: queried from Tableau Cloud each time the report opens.',
        source: `Tableau view${extra.workbook ? ` in “${extra.workbook}”` : ''}, embedded with the same Connected App token.`,
        security: RLS(me),
        why: 'Every report in the library is a published Tableau view, so it inherits the same certified definitions and row-level security as the main dashboards — opening a new report never means trusting a new copy of the data.'
      };
    case 'attention':
      return {
        tag: 'Tableau Pulse',
        freshness: extra.generatedAt
          ? `Pulse brief generated ${new Date(extra.generatedAt).toLocaleString([], { dateStyle: 'medium', timeStyle: 'short' })}; refreshed automatically about every 12 minutes.`
          : 'Pulse brief, refreshed automatically about every 12 minutes.',
        source: 'Tableau Pulse Insight Brief over the Pulse metrics you follow. Every sentence and number comes from Pulse; the portal only lays it out.',
        security: 'Runs as you in Tableau, so Pulse only sees your rows (same row-level security as the dashboards) and only metrics you follow.',
        why: 'Pulse has already computed each metric’s period-over-period change, its top drivers and which direction counts as good — the portal only turns those facts into Issue and Expected rows. Because the metrics are governed definitions, the change shown here is the same number the dashboard and the Agent show; nobody reconciled them, and nobody wrote the analysis.'
      };
    case 'agent':
      return {
        tag: 'Tableau Pulse',
        freshness: 'Live: each answer is generated by Pulse when you ask.',
        source: `Tableau Pulse Insight Brief, limited to the Pulse metrics you follow${extra.source ? ` on ${extra.source}` : ''}.`,
        security: 'Runs as you in Tableau: only your followed metrics, filtered by the same row-level security as the dashboards.',
        why: 'Answers are grounded in governed Pulse metrics rather than a model reading raw tables, so every number the Agent cites is one you can find on the dashboard. Picking a data source limits the Agent to that source’s metrics — the same scoping and security Tableau applies everywhere else in the portal.'
      };
    case 'scorecard':
      return {
        tag: 'Tableau Embedding API',
        freshness: 'Live: read from the embedded dashboard and re-read whenever its filters change.',
        source: `Summary data of the “${extra.worksheet || 'Engagement Performance'}” worksheet, read with the Embedding API (getSummaryDataReaderAsync).`,
        security: 'Exactly the rows the dashboard is allowed to show you — it reads the dashboard, not the database.',
        why: 'This table runs no query of its own: it reads the summary data Tableau already computed for the embedded dashboard, so it can’t disagree with the charts, and it follows the dashboard’s filters and security automatically.'
      };
    case 'reports':
      return {
        tag: 'Tableau REST API',
        freshness: 'Live list from Tableau Cloud; favorites are saved in Tableau, so they follow you into Tableau too.',
        source: 'Tableau REST API: the views in the Apex project that your subscription includes.',
        security: 'Tableau permissions decide what you can open; row-level security applies inside every report.',
        why: 'The list is whatever Apex has published in Tableau for your subscription, and the stars are Tableau favorites — a new report appears here the moment it’s published, with no portal change, and it carries the same certified definitions and security as everything else.'
      };
    case 'feeds':
      return {
        tag: 'VizQL Data Service',
        freshness: 'Live: queried from Tableau every time the link is opened or refreshed in Excel / Sheets.',
        source: `Tableau VizQL Data Service query against “${VI_SOURCE}”, run as you.`,
        security: RLS(me, ['client name', 'service line', 'engagement type']),
        why: 'The spreadsheet gets a live query against the same governed data source as the dashboard, under the same row-level security — not an exported file that goes stale or a second copy someone has to keep in sync.'
      };
    case 'alerts':
      return {
        tag: 'Tableau Pulse + REST',
        freshness: 'Live from Tableau: subscriptions and follows are stored in Tableau, not in the portal.',
        source: 'Tableau REST API (email subscriptions) and the Pulse API (metric follows).',
        security: 'Each email and Pulse digest is rendered as you, so it only ever shows your data.',
        why: 'Email subscriptions and Pulse follows are Tableau features the portal simply manages, so there’s no separate scheduling system to run. Every delivery is rendered as you, so even a forwarded email only ever contains your data.'
      };
    default:
      return null;
  }
}
